"""Tests for scripts/guard_anchors.py (registry-anchored axiom-guard coverage).

The script is what turns the island guard jobs from "printed at least N lines" into "printed,
clean, the theorem of every proved registry node on the island".  These tests pin:

  * name resolution: the gate-matched declaration is fully qualified by the artifact's
    namespaces, and a same-named declaration whose statement differs is NOT picked;
  * output parsing: wrapped axiom lists, `does not depend on any axioms`, primes and
    guillemets in names;
  * failure modes: a missing anchor, an extra axiom, sorryAx, a statement that drifted from
    its artifact, and an island with no proved nodes (must not pass vacuously);
  * parity of the standalone Lean normaliser with telperion.missions.verify;
  * the live registry: every proved node on the four wired islands resolves.

conjecture1_proved = False.
"""
from __future__ import annotations

import importlib.util
import sys
import textwrap
from pathlib import Path

import pytest

TELPERION = Path(__file__).resolve().parents[1]
_spec = importlib.util.spec_from_file_location(
    "guard_anchors", TELPERION / "scripts" / "guard_anchors.py")
ga = importlib.util.module_from_spec(_spec)
sys.modules["guard_anchors"] = ga  # dataclasses resolve the module by name
_spec.loader.exec_module(ga)

CLEAN = "[propext, Classical.choice, Quot.sound]"


# ---------------------------------------------------------------------------
# fixture registry
# ---------------------------------------------------------------------------

ARTIFACT = textwrap.dedent("""\
    import Mathlib
    /-! doc: theorem foo (n : Nat) : n = n := rfl  -- a decoy inside a comment -/
    namespace Outer
    theorem foo (n : Nat) : n + 0 = n := by simp   -- same name, different statement
    namespace Inner
    noncomputable section
    /-- the real one -/
    theorem foo (n : Nat) : n = n := rfl
    end
    end Inner
    end Outer
    namespace A.B
    theorem bar' : True := trivial
    end A.B
    theorem rootThm : 1 = 1 := rfl
    """)


def _stmt(body: str, slug: str) -> str:
    return (f"-- DO NOT EDIT BY HAND — generated by telperion mission; node {slug}; sha256 0\n"
            f"import Mathlib\nopen Outer\n\n{body} := by sorry\n")


def _node(name: str, artifact: str, status: str = "proved") -> str:
    return textwrap.dedent(f"""\
        kind = "lemma"
        name = "{name}"
        status = "{status}"
        title = "t"
        [proof]
        artifact = "{artifact}"
        artifact_kind = "lean_module"
        closure_clean = true
        via = "direct"
        """)


@pytest.fixture()
def registry(tmp_path: Path) -> Path:
    root = tmp_path / "telperion"
    lean = root / "examples" / "isle" / "lean"
    lean.mkdir(parents=True)
    (lean / "Art.lean").write_text(ARTIFACT)
    camp = root / "missions" / "camp"
    (camp / "nodes").mkdir(parents=True)
    (camp / "lean" / "Statements").mkdir(parents=True)
    rel = "../../examples/isle/lean/Art.lean"
    specs = {
        "C_foo": "theorem foo (n : Nat) : n = n",
        "C_bar": "theorem bar' : True",
        "C_root": "theorem rootThm : 1 = 1",
    }
    for slug, body in specs.items():
        (camp / "nodes" / f"{slug}.toml").write_text(_node(slug, rel))
        (camp / "lean" / "Statements" / f"{slug}.lean").write_text(_stmt(body, slug))
    # an open node on the island and a proved node elsewhere are both ignored
    (camp / "nodes" / "C_open.toml").write_text(_node("C_open", rel, status="open"))
    (camp / "nodes" / "C_else.toml").write_text(
        _node("C_else", "../../examples/other/lean/X.lean"))
    return root


def _good_output() -> str:
    return "\n".join([
        f"'Outer.Inner.foo' depends on axioms: {CLEAN}",
        "'A.B.bar'' does not depend on any axioms",
        "'rootThm' depends on axioms: [propext]",
        f"'Outer.foo' depends on axioms: {CLEAN}",
    ])


# ---------------------------------------------------------------------------
# resolution
# ---------------------------------------------------------------------------

def test_load_anchors_qualifies_by_namespace(registry):
    anchors = ga.load_anchors(registry, "isle")
    got = {a.node: a.theorem for a in anchors}
    assert got == {"C_foo": "Outer.Inner.foo", "C_bar": "A.B.bar'", "C_root": "rootThm"}


def test_same_short_name_with_different_statement_is_not_picked():
    # Outer.foo proves `n + 0 = n`; the node states `n = n` -> only Outer.Inner.foo matches.
    stmt = _stmt("theorem foo (n : Nat) : n = n", "C_foo")
    assert ga.resolve_theorem(ARTIFACT, stmt) == "Outer.Inner.foo"


def test_statement_drift_is_a_registry_error():
    stmt = _stmt("theorem foo (n : Nat) : n = n + 1", "C_foo")
    with pytest.raises(ga.RegistryError, match="drift"):
        ga.resolve_theorem(ARTIFACT, stmt)


def test_weakened_conclusion_does_not_match():
    # the gate's rule: the match must be followed by the proof body, not by `∨ True`
    art = "theorem foo (n : Nat) : n = n ∨ True := Or.inr trivial\n"
    with pytest.raises(ga.RegistryError):
        ga.resolve_theorem(art, _stmt("theorem foo (n : Nat) : n = n", "x"))


def test_root_prefix_and_end_of_dotted_namespace():
    art = "namespace X.Y\ntheorem _root_.top : True := trivial\nend X.Y\ntheorem after : True := trivial\n"
    assert ga.resolve_theorem(art, _stmt("theorem _root_.top : True", "x")) == "top"
    assert ga.resolve_theorem(art, _stmt("theorem after : True", "x")) == "after"


def test_private_theorem_is_rejected():
    art = "namespace N\nprivate theorem hid : True := trivial\nend N\n"
    with pytest.raises(ga.RegistryError, match="private"):
        ga.resolve_theorem(art, _stmt("theorem hid : True", "x"))


def test_empty_island_refuses_to_pass(registry, tmp_path, capsys):
    out = tmp_path / "o.txt"
    out.write_text(_good_output())
    rc = ga.main(["--island", "nope", "--telperion", str(registry), str(out)])
    assert rc == 2
    assert "vacuously" in capsys.readouterr().out


