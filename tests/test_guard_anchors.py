@pytest.mark.parametrize("src", [
    ARTIFACT,
    "theorem x : \"--not a comment\" = \"/-\" := rfl -- tail\n",
    "/- a /- nested -/ still -/ theorem y : True := by sorry",
    "lemma z   :\n  True\n:= sorry",
])
def test_normaliser_parity_with_verify(src):
    verify = pytest.importorskip("telperion.missions.verify")
    assert ga.strip_lean_comments(src) == verify._strip_lean_comments(src)
    assert ga.normalize_lean(src) == verify.normalize_lean(src)
    assert ga.strip_string_literals(src) == verify._strip_string_literals(src)


