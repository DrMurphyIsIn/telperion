def test_good_output_passes(registry, tmp_path):
    out = tmp_path / "o.txt"
    out.write_text(_good_output())
    assert ga.main(["--island", "isle", "--telperion", str(registry), str(out)]) == 0


def test_multiple_output_files_are_unioned(registry, tmp_path):
    lines = _good_output().split("\n")
    a, b = tmp_path / "a.out", tmp_path / "b.out"
    a.write_text("\n".join(lines[:2]))
    b.write_text("\n".join(lines[2:]))
    assert ga.main(["--island", "isle", "--telperion", str(registry), str(a), str(b)]) == 0


def test_wrapped_axiom_list_is_joined():
    anchors = [ga.Anchor("n", "c", Path("x"), "Outer.Inner.foo")]
    text = "'Outer.Inner.foo' depends on axioms: [propext,\n  Classical.choice,\n  Quot.sound]\n"
    assert ga.check(anchors, text) == []


def test_missing_anchor_fails(registry, tmp_path, capsys):
    out = tmp_path / "o.txt"
    # only the decoy Outer.foo is printed, not the node theorem Outer.Inner.foo
    out.write_text(_good_output().replace("'Outer.Inner.foo'", "'Outer.Inner.fooX'"))
    assert ga.main(["--island", "isle", "--telperion", str(registry), str(out)]) == 1
    assert "`Outer.Inner.foo` is never printed" in capsys.readouterr().out


def test_extra_axiom_fails(registry, tmp_path, capsys):
    out = tmp_path / "o.txt"
    out.write_text(_good_output().replace(
        f"'Outer.Inner.foo' depends on axioms: {CLEAN}",
        "'Outer.Inner.foo' depends on axioms: [propext, Classical.choice,\n Quot.sound, cheat]"))
    assert ga.main(["--island", "isle", "--telperion", str(registry), str(out)]) == 1
    assert "non-standard axioms ['cheat']" in capsys.readouterr().out


def test_sorry_anywhere_fails(registry, tmp_path):
    out = tmp_path / "o.txt"
    out.write_text(_good_output() + "\n'Unrelated.x' depends on axioms: [sorryAx]\n")
    assert ga.main(["--island", "isle", "--telperion", str(registry), str(out)]) == 1


def test_duplicate_print_must_all_be_clean():
    anchors = [ga.Anchor("n", "c", Path("x"), "T")]
    text = f"'T' depends on axioms: {CLEAN}\n'T' depends on axioms: [propext, bad]\n"
    assert ga.check(anchors, text)


def test_guillemets_are_canonicalised():
    anchors = [ga.Anchor("n", "c", Path("x"), "A.lam₀")]
    assert ga.check(anchors, f"'A.«lam₀»' depends on axioms: {CLEAN}") == []


def test_empty_guard_output_fails(registry, tmp_path):
    out = tmp_path / "o.txt"
    out.write_text("")
    assert ga.main(["--island", "isle", "--telperion", str(registry), str(out)]) == 1


