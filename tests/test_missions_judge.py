"""Tests for telperion.missions.judge: Comparator challenges from registered statements.

Pins, on a synthetic island and on the live registry:

  * the bridge module's TYPE is the registered statement (binders and conclusion verbatim,
    binders lifted into a `forall`), its PROOF is the artifact's fully qualified theorem, it
    imports the artifact and the island's AxiomGuard libs, and it keeps the statement's own
    `open` lines;
  * the signature splitter finds the top-level colon past binders that contain colons, and
    the last top-level `:=`;
  * a statement that declares anything besides its theorem is refused, per node, and reported
    as not consumable without sinking the island;
  * the config is self-check over the bridge theorem with the three standard axioms, nanoda on;
  * the Comparator tag follows the island toolchain (not the BG bridge's v4.32.0);
  * `--check` reports a stale, missing or extra file; `--shard I/N` partitions the nodes;
  * an out-of-tree island (bg: proof/formalization) path-requires its own directory and, with
    no AxiomGuard lib, imports the vocabulary mirror's home modules instead;
  * the live dbn, rvm_bridge, zeta_reflection and bg bundles are committed and in sync with
    the registry, and li_positivity renders (it is not yet in the CI matrix).

conjecture1_proved = False.
"""
from __future__ import annotations

