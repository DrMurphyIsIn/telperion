    b = judge.build_bundle(tel, "isl")
    out = tmp_path / "bundle"
    judge.write_bundle(b, out)
    assert sorted(p.name for p in out.iterdir()) == sorted(
        ["MANIFEST.json", "MissionChallenges", "MissionChallenges.lean", "X_node.comparator.json",
         "lakefile.toml", "lean-toolchain"])
    assert (out / "lean-toolchain").read_text().strip() == "leanprover/lean4:v4.34.0-rc1"
    lakefile = (out / "lakefile.toml").read_text()
    assert 'name = "Isl"' in lakefile and 'path = "../../../examples/isl/lean"' in lakefile
    assert (out / "MissionChallenges.lean").read_text() == "import MissionChallenges.X_node\n"
    man = json.loads((out / "MANIFEST.json").read_text())
    assert man["comparator_tag"] == "v4.34.0-rc1"
    assert man["nodes"][0]["theorem"] == "Isl.Deep.node_thm"
    assert man["nodes"][0]["bridge_theorem"] == "MissionJudge.X_node"
    assert judge.check_bundle(b, out) == []
