def test_split_signature_handles_colons_in_binders_and_ascriptions():
    body = ("theorem t (f : ℕ → ℕ) {s : Set ℕ} [h : DecidableEq ℕ] ⦃k : ℕ⦄ :\n"
            "    (⟨1, by decide⟩ : Fin 2) = ⟨1, by decide⟩ ∧ ∀ x : ℕ, f x = (x : ℕ) := by sorry")
    short, binders, concl = judge.split_signature(body)
    assert short == "t"
    assert binders == "(f : ℕ → ℕ) {s : Set ℕ} [h : DecidableEq ℕ] ⦃k : ℕ⦄"
    assert concl == "(⟨1, by decide⟩ : Fin 2) = ⟨1, by decide⟩ ∧ ∀ x : ℕ, f x = (x : ℕ)"


def test_split_signature_keeps_let_assignments_inside_the_conclusion():
    body = "theorem t : (let y := 2; y = 2) := by sorry"
    assert judge.split_signature(body)[2] == "(let y := 2; y = 2)"


def test_split_signature_refuses_extra_declarations():
    with pytest.raises(judge.JudgeError, match="declares `def`"):
        judge.split_signature("def helper : ℕ := 1\n\ntheorem t : helper = 1 := by sorry")
    with pytest.raises(judge.JudgeError, match="declares `namespace`"):
        judge.split_signature("namespace N\ntheorem t : True := by sorry\nend N")
    with pytest.raises(judge.JudgeError, match="expected exactly one"):
        judge.split_signature("theorem a : True := by sorry\ntheorem b : True := by sorry")


