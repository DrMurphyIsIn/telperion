HEADER = "-- DO NOT EDIT BY HAND — generated by telperion mission; node {slug}; sha256 0123456789abcdef\n"
LAKEFILE = ('name = "Isl"\ndefaultTargets = ["Art", "AxiomGuardIsl"]\n\n[[lean_lib]]\nname = "Art"\n\n'
            '[[lean_lib]]\nname = "Vocab"\n\n[[lean_lib]]\nname = "AxiomGuardIsl"\n')


def _island(tmp_path: Path, *, artifact: str, statement: str, slug="X_node", campaign="x",
            status="proved", artifact_name="Art.lean", extra_nodes=()) -> Path:
    """A minimal telperion/ tree: one island with one artifact, one campaign with one node."""
    tel = tmp_path / "telperion"
    lean = tel / "examples" / "isl" / "lean"
    lean.mkdir(parents=True)
    (lean / "lakefile.toml").write_text(LAKEFILE)
    (lean / "lean-toolchain").write_text("leanprover/lean4:v4.34.0-rc1\n")
    (lean / artifact_name).parent.mkdir(parents=True, exist_ok=True)
    (lean / artifact_name).write_text(artifact)
    camp = tel / "missions" / campaign
    (camp / "nodes").mkdir(parents=True)
    (camp / "lean" / "Statements").mkdir(parents=True)
    (camp / "mission.toml").write_text(
        f'name = "{campaign}.goal"\ntitle = "t"\ndescription = "d"\ngoal_node = "{slug}"\n'
        'environment_toolchain = "leanprover/lean4:v4.34.0-rc1"\nenvironment_mathlib_rev = "x"\n')
    for sl, st, art_text, art_name in ((slug, statement, artifact, artifact_name), *extra_nodes):
        if art_name != artifact_name:
            (lean / art_name).write_text(art_text)
        (camp / "nodes" / f"{sl}.toml").write_text(textwrap.dedent(f"""\
            name = "{sl.replace('_', '.', 1)}"
            title = "node"
            kind = "lemma"
            status = "{status}"
            statement_module = "Statements.{sl}"
            depends_on = []

            [proof]
            artifact = "../../examples/isl/lean/{art_name}"
            artifact_kind = "lean_module"
            via = "direct"
            closure_clean = true
            """))
        (camp / "lean" / "Statements" / f"{sl}.lean").write_text(HEADER.format(slug=sl) + st)
    return tel


ARTIFACT_NS = textwrap.dedent("""\
    import Mathlib
    import Vocab
    open Real

    namespace Isl.Deep
    /-- the node theorem -/
    theorem node_thm {x : ℝ} (hx : 0 < x) [inst : Nonempty ℕ] : 0 < x ^ 2 := by
      positivity
    end Isl.Deep
    """)
STATEMENT_NS = ("import Statements.Defs\nopen Real\n\n"
                "theorem node_thm {x : ℝ} (hx : 0 < x) [inst : Nonempty ℕ] : 0 < x ^ 2 := by sorry\n")


def test_bridge_module_has_registered_type_and_artifact_proof(tmp_path):
    tel = _island(tmp_path, artifact=ARTIFACT_NS, statement=STATEMENT_NS)
    b = judge.build_bundle(tel, "isl")
    assert b.toolchain == "leanprover/lean4:v4.34.0-rc1" and b.comparator_tag == "v4.34.0-rc1"
    assert b.package == "Isl" and b.skipped == ()
    [c] = b.challenges
    assert c.theorem == "Isl.Deep.node_thm" and c.solution_module == "Art"
    assert c.challenge_module == "MissionChallenges.X_node"
    assert c.bridge_theorem == "MissionJudge.X_node"
    text = c.challenge_text
    # imports: the artifact, then the island's AxiomGuard libs; never the campaign mirror
    assert "import Art\nimport AxiomGuardIsl\n" in text and "Statements.Defs" not in text
    # the ARTIFACT's open lines and namespace, not the statement file's
    assert "\nopen Real\n" in text
    assert "\nnamespace Isl.Deep\n" in text and text.rstrip().endswith("end Isl.Deep")
    # the registered signature, binders lifted into a forall, conclusion verbatim
    assert "theorem _root_.MissionJudge.X_node :\n" in text
    assert "∀ {x : ℝ} (hx : 0 < x) [inst : Nonempty ℕ], 0 < x ^ 2 :=" in text
    # proved by the artifact's fully qualified constant, nothing else
    assert ":=\n  Isl.Deep.node_thm\n" in text
    assert "sorry" not in text.split("-/", 1)[1]
    assert "DO NOT EDIT BY HAND" in text
    # config: self-check over the bridge theorem
    assert c.config["challenge_module"] == c.config["solution_module"] == "MissionChallenges.X_node"
    assert c.config["theorem_names"] == ["MissionJudge.X_node"]
    assert set(c.config["permitted_axioms"]) == {"propext", "Quot.sound", "Classical.choice"}
    assert c.config["enable_nanoda"] is True


