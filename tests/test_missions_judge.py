    assert any(p.startswith("stale: MissionChallenges/X_node.lean") for p in judge.check_bundle(b, out))
    (out / "stray.lean").write_text("")
    assert any("unexpected file in bundle: stray.lean" == p for p in judge.check_bundle(b, out))
    (out / "X_node.comparator.json").unlink()
    assert any("missing: X_node.comparator.json" == p for p in judge.check_bundle(b, out))


